"""Cross-layer scalar Green's function for layered soil (ADR-0007).

This module implements the electric (scalar-potential) Green's
function for a 2-layer soil where source and observer can be in
**either** layer. It complements the existing image-series solver in
:mod:`groundfield.solver.image_2layer` (which assumes both points in
the upper layer) and the Sommerfeld kernel in
:mod:`groundfield.solver.mom_sommerfeld` (same restriction).

Mathematical background
-----------------------
For a 2-layer soil with upper-layer resistivity $\\rho_1$ and
thickness $h_1$, lower-layer resistivity $\\rho_2$ semi-infinite,
the scalar Green's function for a unit point source at depth $z_s$
observed at depth $z$ takes the Hankel-transform form

$$
\\varphi(s, z, z_s) \\;=\\; \\int_0^{\\infty}\\!
\\Phi(\\lambda, z, z_s)\\,J_0(\\lambda s)\\,\\lambda\\,d\\lambda,
$$

where the spectral kernel $\\Phi(\\lambda, z, z_s)$ is determined by
the boundary-value problem

- $\\partial\\Phi/\\partial z = 0$ at $z = 0$ (free surface),
- $\\Phi$ continuous at $z = h_1$,
- $\\sigma_k\\,\\partial\\Phi/\\partial z$ continuous at $z = h_1$.

In each layer $\\Phi$ is a sum of $e^{\\pm\\lambda z}$ plus a
particular solution $e^{-\\lambda|z-z_s|}/(2\\lambda\\sigma_k)$ in
the layer that contains the source. The four layer-pair cases —
$\\Phi_{uu}, \\Phi_{ul}, \\Phi_{lu}, \\Phi_{ll}$ — correspond to
the four (source-layer, observer-layer) combinations and are
related by reciprocity ($\\Phi_{ul} = \\Phi_{lu}$).

Implementation
--------------
The 4×4 boundary-value system is solved numerically once per
$(\\lambda, z_s)$ pair (4 unknowns: amplitudes in each layer for
each direction). Per call the cost is dominated by $J_0$
evaluation and the linear solve at each $\\lambda$ node — fully
vectorisable with `numpy`.

The implementation focuses on the 2-layer case
(:class:`groundfield.soil.models.TwoLayerSoil`); the n-layer
extension follows the same recursion and is deferred to ADR-0007
Phase C.

Numerical strategy
------------------
The Hankel inversion is split into an analytic and a numerical
part, because the two halves of $\\Phi$ behave completely
differently in $\\lambda$:

1. **Primary term** — the particular solution
   $\\rho_k/(2\\lambda)\\,e^{-\\lambda|z-z_s|}$ in the layer that
   contains the source. It does *not* decay when
   $|z - z_s| \\to 0$, and its Hankel inverse is known exactly,
   $\\rho_k/(2R)$ with $R = \\sqrt{s^2 + (z-z_s)^2}$. It is
   therefore evaluated in closed form
   (:func:`_primary_term_real_space`). Integrating it numerically
   instead — as versions up to 0.14.1 did — truncates at
   $\\lambda_\\text{max}$ and leaves an
   $O((\\lambda_\\text{max}R)^{-1/2})$ residue that *oscillates* in
   $s$ with period $2\\pi/\\lambda_\\text{max}$: up to 4.5 % on the
   total kernel, and non-monotone in ``lambda_max_factor``.
2. **Reflected remainder** — everything generated by the free
   surface and the interface. It is a superposition of image terms
   $c_j/(2\\lambda)\\,e^{-\\lambda d_j}$ (:func:`_image_generation`
   gives the exact coefficients and distances), so it decays like
   $e^{-\\lambda d_\\text{img}}$ with $d_\\text{img} = \\min_j d_j$
   the smallest image distance — but **only** in proportion to that
   distance. Every image distance can degenerate to zero
   ($z + z_s \\to 0$ for a surface pair, $|2h_1 - z - z_s| \\to 0$
   for a pair at the interface, $z_l - z_u \\to 0$ for a cross-layer
   pair straddling it), and then the remainder does not decay at all
   and truncating it is *not* safe. Versions up to 0.15.0.dev sized
   $\\lambda_\\text{max}$ from $\\min(h_1, s + z + z_s)$, which has no
   relation to $d_\\text{img}$, and were consequently wrong by 0.7 %
   … 40 % on such pairs with no warning (review pass 9 re-audit).
   Since 0.15.0 the truncation is *guaranteed*: every image term with
   $\\lambda_\\text{max} d_j < 30$ is subtracted from the spectral
   integrand and added back through its exact Hankel inverse
   $c_j/(2\\sqrt{s^2 + d_j^2})$
   (:func:`_reflected_image_terms`), so the numerically integrated
   rest provably decays like $e^{-\\lambda d_\\text{rest}}$ with
   $\\lambda_\\text{max} d_\\text{rest} \\ge 30$ and the discarded tail
   is bounded by $e^{-30} \\approx 10^{-13}$. The rest goes through
   the split-grid quadrature (:func:`_hankel_lambda_grid`):
   logarithmic nodes below the first $J_0$ oscillation, then one
   Gauss panel per oscillation period, with a documented resolution
   floor of eight nodes per period and a
   :class:`SommerfeldResolutionWarning` when the allocation budget
   cannot meet it.

Because the tail bound above is analytic, $\\lambda_\\text{max}$ no
longer has to be large — it only has to be *consistent* with the set
of subtracted image terms. That is what makes the cost of a remote
pair bounded: the node count of the oscillation-resolved grid grows
like $\\lambda_\\text{max}\\,s$, so the module caps
$\\lambda_\\text{max}$ at :data:`_HANKEL_PANEL_TARGET` panels (scaled
by ``lambda_max_factor / 200``) and subtracts as many image terms as
that cap requires (:func:`_plan_truncation`). A 4 km pair costs the
same as a 90 m one, and ``lambda_max_factor`` becomes a genuine
convergence knob: raising it moves work from the closed form into the
quadrature and *must not* change the answer.

Because the numerically integrated rest is analytic in
$t = \\ln(s + c)$ — and, after the image split above, has no scale
shorter than $d_\\text{rest}$, which is what $c$ is set to —
reaction blocks with many distance pairs at one $(z, z_s)$ are
evaluated on a range-sized log grid and cubic-spline interpolated
instead of pair by pair (~1e-6 relative, worst case 3e-5; see
:func:`two_layer_layered_correction_group`).

Limit checks (in the test suite)
--------------------------------
- $\\rho_2 = \\rho_1$: all four pair kernels reduce to the
  homogeneous Green's function $\\rho/(4\\pi r) + \\rho/(4\\pi r')$.
- $\\rho_2 \\to \\infty$ (PEC bottom): for source in upper layer,
  $G_{ul} \\to 0$ (no penetration into the lower layer);
  $G_{uu} \\to G_{uu}^{K \\to 1}$ — image structure with
  $K \\to 1$.
- $\\rho_2 \\to 0$ (sink): $G_{uu} \\to G_{uu}^{K \\to -1}$,
  spreading resistance drops dramatically.
- Source/observer in upper layer: bit-exact match to the
  Tagg/Sunde image series in
  :func:`groundfield.solver.image_2layer.solve_image_2layer`.

References
----------
- Sunde, E. D. (1968). *Earth Conduction Effects in Transmission
  Systems*, Dover, Ch. 3.
- Tagg, G. F. (1964). *Earth Resistances*, Newnes.
- Wait, J. R. (1972). *Electromagnetic Waves in Stratified Media*,
  Pergamon.
"""

from __future__ import annotations

import math
import warnings
from typing import NamedTuple

import numpy as np
from scipy.interpolate import CubicSpline
from scipy.special import j0
from functools import lru_cache


class SommerfeldResolutionWarning(UserWarning):
    """The Sommerfeld quadrature could not resolve the $J_0$ oscillations.

    The linear region of the Hankel grid places one Gauss panel per
    $J_0(\\lambda s)$ period, so the node count grows like
    $\\lambda_\\text{max}\\,s$. A hard node budget
    (:data:`_HANKEL_MAX_LINEAR_NODES`) bounds the transient allocation;
    when that budget forces fewer than
    :data:`_HANKEL_MIN_NODES_PER_OSCILLATION` nodes per period the
    quadrature is no longer converged and this warning is raised
    instead of returning a silently wrong number (a coarse grid on an
    oscillatory integrand does not merely lose digits — it can flip the
    sign of the result).

    The remedy is always to *lower* ``lambda_max_factor`` or to reduce
    the horizontal distance range of the group. Lowering the factor
    does **not** lose accuracy: the truncated tail is subtracted in
    closed form (:func:`_reflected_image_terms`), so a smaller
    $\\lambda_\\text{max}$ only moves work from the quadrature into the
    exact image sum. Silence with
    ``warnings.simplefilter("ignore", SommerfeldResolutionWarning)``
    only if the affected entries are known to be negligible.
    """


class SommerfeldTailTruncationWarning(UserWarning):
    """The $\\lambda$-truncated tail of the reflected kernel is not bounded.

    Sibling of :class:`SommerfeldResolutionWarning`: that one reports a
    grid too *coarse* to follow $J_0(\\lambda s)$, this one a grid too
    *short* to have integrated the reflected remainder.

    The reflected part of $\\Phi$ is a superposition of image terms
    $c_j/(2\\lambda)\\,e^{-\\lambda d_j}$, so truncating the Hankel
    integral at $\\lambda_\\text{max}$ discards
    $\\sum_j c_j/2 \\int_{\\lambda_\\text{max}}^\\infty e^{-\\lambda d_j}
    J_0(\\lambda s)\\,d\\lambda$, bounded by
    $\\sum_j |c_j| e^{-\\lambda_\\text{max} d_j}/(2 d_j)$. The bound is
    only small if $\\lambda_\\text{max} d_j$ is large for **every**
    retained term, and $d_j$ has nothing to do with the historic
    $\\lambda_\\text{max} = $ ``lambda_max_factor`` $/\\min(h_1, s + z +
    z_s)$: a pair at the air/soil surface ($z + z_s \\to 0$), at the
    layer interface ($|2h_1 - z - z_s| \\to 0$) or straddling it has
    $d_j \\to 0$ and a tail of order one. Review pass 9 measured
    −39.5 % on such a pair with *no* diagnostic; the failure grows as
    a mesh is refined towards the interface, which is what makes it
    release-blocking rather than cosmetic.

    Every term with $\\lambda_\\text{max} d_j <
    $ :data:`_HANKEL_TAIL_DECAY_TARGET` is therefore taken out of the
    quadrature and inverted in closed form. This warning fires when
    that could **not** be completed — in practice only when the term
    budget :data:`_HANKEL_IMAGE_TERM_BUDGET` is exhausted, which needs
    a very thin top layer, $|K| \\to 1$ and a multi-kilometre span at
    once. The result is then not bounded by the documented tolerance:
    lower ``lambda_max_factor`` (fewer image terms are needed), reduce
    the distance range, or raise the budget.
    """

# Peak-memory budget (bytes) for the dense ``J0(lambda * s)`` Bessel
# matrix that the Hankel contractions below would otherwise materialise
# in one shot. For a cross-layer grounding grid the number of distance
# pairs is ``n_seg**2`` and the oscillation-resolved lambda grid reaches
# ~5e4 nodes, so the full matrix can exceed 100 GiB. The contraction is
# blocked over the distance axis to keep the transient allocation below
# this budget; row-blocking a matmul is bit-for-bit identical to the
# single-shot form (see ``tests/test_layered_green_chunking.py``).
_HANKEL_MATMUL_BUDGET_BYTES = 512 * 1024 * 1024

# --- Oscillation resolution of the linear (large-lambda) region -------
#
# The linear region of the Hankel grid places one Gauss panel of order
# ``_HANKEL_PANEL_ORDER`` per J0 period ``2 pi / s``, so the node count
# grows like ``lambda_max * s``. The historic code clamped that at 4096
# panels with no accuracy check, which silently degraded to ~2.7 nodes
# per oscillation and flipped the sign of the result (review pass 9,
# finding F14). The resolution is now a *policy* with three tiers:
#
#   1. up to ``_HANKEL_SOFT_LINEAR_NODES`` (= the historic 4096 panels
#      x 16 nodes) the full one-panel-per-period target is used, so
#      every problem the historic cap handled stays bit-identical;
#   2. beyond that the panel count is only reduced down to the
#      ``_HANKEL_MIN_NODES_PER_OSCILLATION`` floor — the very same
#      8-nodes-per-oscillation adequacy criterion the single-panel fast
#      path below uses — so the node count keeps scaling with the
#      oscillation content instead of being clamped;
#   3. ``_HANKEL_MAX_LINEAR_NODES`` (1 Mi nodes ~= 75 MiB for the
#      (n_lambda, 3, 3) amplitude system) is a hard allocation budget.
#      If it forces fewer nodes per oscillation than the floor, a
#      :class:`SommerfeldResolutionWarning` is emitted rather than a
#      silently unconverged number.
_HANKEL_PANEL_ORDER = 16
_HANKEL_MIN_NODES_PER_OSCILLATION = 8.0
_HANKEL_SOFT_LINEAR_NODES = 1 << 16
_HANKEL_MAX_LINEAR_NODES = 1 << 20

# --- Truncation of the reflected tail (review pass 9 re-audit) --------
#
# The reflected kernel is the exact image superposition
# ``sum_j c_j/(2 lambda) exp(-lambda d_j)`` (see
# :func:`_image_generation`), so truncating the Hankel integral at
# ``lambda_max`` discards a tail bounded by
# ``sum_j |c_j| exp(-lambda_max d_j)/(2 d_j)``. ``lambda_max`` must
# therefore be sized against the *image distances*, not against
# ``min(h_1, s + z + z_s)``: every term is required to satisfy
# ``lambda_max * d_j >= _HANKEL_TAIL_DECAY_TARGET`` and every term that
# does not is subtracted from the integrand and added back through its
# exact Hankel inverse ``c_j/(2 sqrt(s^2 + d_j^2))``.
#
# ``exp(-30) = 9.4e-14``, i.e. ~9 orders below the module's documented
# 1e-4 kernel tolerance even after the ``s/d_j`` amplification of the
# bound relative to the term's own real-space size.
_HANKEL_TAIL_DECAY_TARGET = 30.0
# Once the split is in place there is no point integrating far beyond
# where the residual integrand has died: nodes spent there are nodes
# taken away from the region that carries the integral. ``lambda_max``
# is therefore also capped at ``MARGIN * TARGET / d_rest`` — a tail of
# ``exp(-120)``, i.e. every bit of margin one could want, while keeping
# the uniform panels of the linear region narrow enough to resolve
# ``exp(-lambda d_rest)``. Without this cap a large ``lambda_max_factor``
# put the whole integrand inside the first panel and *lost* accuracy
# (measured −4.4e-6 at factor 1000 for z = z_s = h_1, against −5e-10 at
# factor 300 — non-monotone in the public knob all over again).
_HANKEL_TAIL_DECAY_MARGIN = 4.0
# Terms below this fraction of ``max(rho)`` are left in the quadrature
# whatever their distance: they cannot matter at the module's tolerance
# (the image coefficients fall off like ``|K|^m``, so this is what
# terminates the term generation for a thin top layer).
_HANKEL_IMAGE_COEFF_FLOOR = 1e-17
# Hard cap on the number of closed-form image terms per (z, z_s) pair.
# Reaching it raises :class:`SommerfeldTailTruncationWarning`.
_HANKEL_IMAGE_TERM_BUDGET = 2048

# --- Cost policy for the oscillation-resolved grid --------------------
#
# The linear region carries one panel per J0 period, so its node count
# grows like ``lambda_max * s``. Because the discarded tail is bounded
# *analytically* (above) rather than by making ``lambda_max`` large,
# ``lambda_max`` may be lowered until the panel count fits this target,
# paying for it with a few more closed-form image terms. Without the
# cap a 4 km pair cost 42x a 90 m one (review pass 9 re-audit, item 3);
# with it the cost of a remote pair is bounded and, at the default
# knob, below v0.14.1 for every span beyond ~160 m.
#
# The target scales with ``lambda_max_factor / _HANKEL_PANEL_TARGET_AT``
# so that the public knob keeps its meaning: raising it really does
# raise ``lambda_max`` (and lower the number of closed-form terms),
# which is what makes a convergence check in that knob meaningful.
_HANKEL_PANEL_TARGET = 1024
_HANKEL_PANEL_TARGET_AT = 200.0

# --- Large-group interpolation policy ---------------------------------
#
# Above ``_HANKEL_INTERP_THRESHOLD`` distance pairs in one (z, z_s)
# group the *reflected* part of the kernel — smooth and analytic in the
# horizontal distance ``s`` because the singular primary 1/R term is
# split off in closed form (:func:`_primary_term_real_space`) — is
# sampled on a log-spaced ``s``-grid and interpolated by a not-a-knot
# cubic spline instead of being contracted at every pair. That turns
# whole-grid reaction blocks from O(n_pairs · n_lambda) into
# O(n_nodes · n_lambda), which is what makes a cross-layer grounding
# grid (n_pairs = n_seg**2) tractable in both time and memory.
#
# The node count is sized from the *actual* dynamic range of the group,
# ``t = log(s + c)`` spanning ``t_hi - t_lo``, at
# ``_HANKEL_INTERP_NODES_PER_LN`` nodes per e-fold (~28 per decade).
# A fixed node count (historically 48) meets its accuracy target only
# on the narrow ``s``-range it was tuned for and degrades to ~1 % over
# a 0…400 m network span. Interpolation is skipped whenever it would
# need at least as many nodes as there are pairs, so the switch at the
# threshold is not observable at the module's tolerance.
#
# Measured agreement between the two branches (0.15.0, ten geometries
# incl. surface, interface, near-interface and cross-layer pairs, spans
# up to 4 km, and every group size from 60 to 129 pairs): ~1e-6
# typical, worst case 1.1e-5. The worst case is a surface pair at
# ``s -> 0``, where the *scalar* branch is the less accurate of the two
# (the 32-node logarithmic region under-resolves a sharply decaying
# integrand there); against an independently derived closed form the
# interpolated branch is 4e-7 on that same geometry. Do not restate
# this as "~1e-8" — that claim was in the source at 0.15.0.dev and was
# 2–3 orders optimistic.
_HANKEL_INTERP_THRESHOLD = 64
_HANKEL_INTERP_NODES_PER_LN = 12.0
_HANKEL_INTERP_NODES_MIN = 48
_HANKEL_INTERP_NODES_MAX = 4096


def _hankel_contract(
    lambdas: np.ndarray, s_values: np.ndarray, w_phi: np.ndarray
) -> np.ndarray:
    """Blocked evaluation of ``J0(lambdas * s) @ w_phi`` over ``s``.

    Equivalent to ``j0(lambdas[None, :] * s_values[:, None]) @ w_phi``
    but never materialises the full ``(n_s, n_lambda)`` Bessel matrix:
    the distance axis is processed in row blocks sized so each transient
    ``J0`` block stays within :data:`_HANKEL_MATMUL_BUDGET_BYTES`. The
    result is identical to the single-shot contraction (a matmul is a
    row-independent reduction), so accuracy is unchanged; only peak
    memory is bounded. ``s_values`` of any shape is accepted and the
    original shape is preserved on return.
    """
    orig_shape = s_values.shape
    flat = np.ascontiguousarray(s_values, dtype=float).ravel()
    n_lambda = int(lambdas.shape[0])
    chunk = max(1, _HANKEL_MATMUL_BUDGET_BYTES // (8 * max(n_lambda, 1)))
    if flat.shape[0] <= chunk:
        return (j0(lambdas[None, :] * flat[:, None]) @ w_phi).reshape(orig_shape)
    out = np.empty(flat.shape[0], dtype=float)
    for a in range(0, flat.shape[0], chunk):
        b = a + chunk
        out[a:b] = j0(lambdas[None, :] * flat[a:b, None]) @ w_phi
    return out.reshape(orig_shape)


def _hankel_contract_smooth(
    lambdas: np.ndarray,
    s_values: np.ndarray,
    w_phi: np.ndarray,
    *,
    c: float,
) -> np.ndarray:
    """Contract a **smooth** Hankel weight over many distances.

    Mathematically identical to :func:`_hankel_contract`; the only
    difference is that for large groups the result is obtained from a
    cubic spline through log-spaced sample distances instead of one
    ``J0`` evaluation per pair. Admissible only for weights whose
    Hankel transform is analytic in ``s`` — i.e. after the singular
    primary term has been split off by
    :func:`_primary_term_real_space`.

    Parameters
    ----------
    lambdas, w_phi
        Quadrature nodes and the pre-multiplied weight
        ``Phi_reflected * weights * lambdas``.
    s_values
        Horizontal distances of the group, any shape.
    c
        Offset of the log coordinate $t = \\ln(s + c)$. Chosen as the
        vertical separation (floored at 1 mm) so that $t$ resolves both
        the plateau at $s \\ll |z - z_s|$ and the $1/s$ decay beyond.

    Returns
    -------
    np.ndarray
        Same shape as ``s_values``.
    """
    s_values = np.asarray(s_values, dtype=float)
    n_pairs = int(s_values.size)
    s_min = float(s_values.min())
    s_max = float(s_values.max())
    c = max(float(c), 1e-3)
    t_lo = math.log(s_min + c)
    t_hi = math.log(max(s_max + c, s_min + c + 1e-9))
    if t_hi - t_lo < 1e-9:
        # Degenerate group (all pairs at the same distance).
        value = float(_hankel_contract(lambdas, np.array([s_min]), w_phi)[0])
        return np.full(s_values.shape, value, dtype=float)
    n_nodes = _interp_node_count(t_lo, t_hi)
    if n_pairs <= _HANKEL_INTERP_THRESHOLD or n_nodes >= n_pairs:
        # Interpolation would cost at least as much as the exact
        # contraction — take the exact branch. This also keeps the step
        # at the threshold below the module's tolerance: the two
        # branches only ever meet where they agree to ~1e-6 (worst
        # measured 1.1e-5, see _HANKEL_INTERP_* above) — *not* to
        # ~1e-8, as this comment claimed at 0.15.0.dev.
        return _hankel_contract(lambdas, s_values, w_phi)
    t_nodes = np.linspace(t_lo, t_hi, n_nodes)
    s_nodes = np.maximum(np.exp(t_nodes) - c, 0.0)
    g_nodes = _hankel_contract(lambdas, s_nodes, w_phi)
    spline = CubicSpline(t_nodes, g_nodes)
    flat = spline(np.log(s_values.ravel() + c))
    return np.asarray(flat, dtype=float).reshape(s_values.shape)


@lru_cache(maxsize=None)
def _leggauss_cached(n: int):
    """Gauss-Legendre-Knoten/Gewichte fuer feste Ordnung ``n`` (gecacht).

    ``numpy.polynomial.legendre.leggauss`` loest je Aufruf ein
    Eigenwertproblem (O(n^3)). Im ADR-0007-Cross-Layer-Pfad wird die
    Quadratur pro Segmentpaar mit denselben festen Ordnungen
    (``n_log=32``, ``n_lin=96``) aufgerufen; ohne Cache dominiert der
    wiederholte Knotenaufbau die Laufzeit. Die Rueckgabe wird nur
    gelesen (keine In-place-Mutation), daher ist das Teilen sicher.
    """
    return np.polynomial.legendre.leggauss(n)


