def test_evaluate_spec_does_not_run_code_from_a_formula(tmp_path: Path) -> None:
    marker = tmp_path / "marker.txt"
    payload = f"__import__('pathlib').Path({str(marker)!r}).write_text('ran')*0 + rho"
    try:
        with pytest.raises(EvaluateSpecError, match="not allowed"):
            evaluate_spec(_spec(payload), [50.0], 100.0)
    finally:
        assert not marker.exists(), "the formula string was executed"


def test_load_bustype_json_rejects_code_with_an_actionable_error(
    tmp_path: Path,
) -> None:
    marker = tmp_path / "marker.txt"
    path = tmp_path / "bustype.json"
    doc = _document(f"__import__('os').remove({str(marker)!r}) or rho")
    path.write_text(json.dumps(doc), encoding="utf-8")
    with pytest.raises(EvaluateSpecError) as excinfo:
        load_bustype_json(path)
    message = str(excinfo.value)
    assert "BusType document 'corpus'" in message
    assert "impedance_formula" in message
    assert "(U+0027)" in message  # names the quote character it refuses
    assert "never runs it as code" in message
    assert not marker.exists()


@pytest.mark.parametrize("entry", REJECT, ids=[e["id"] for e in REJECT])
def test_every_rejected_formula_is_rejected_quickly_in_a_worker_process(
    entry: dict, worker_outcomes: dict[str, dict]
) -> None:
    """Each string in a separate process with a deadline: rejected in under
    a second. On the base of the fixsec stream 15 of the strings added for
    SymPy's eager evaluation (rational powers of large integers, also
    through ``exp(c*log(x))``) did not finish within 20 s, three took 1.8 s
    to 2.6 s and one was accepted."""
    result = worker_outcomes[entry["id"]]
    assert result["outcome"] == "rejected", result
    assert result["seconds"] < WORKER_TIME_LIMIT_S, result


