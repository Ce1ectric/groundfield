def test_complex_numbers_with_large_fractions_are_evaluated_quickly(
    text: str, value
) -> None:
    """Both took 1.2 s and 1.4 s in a fresh process on the base of this
    change (SymPy factorised ``2*r**2`` and ``r**2 + (r/3)**2`` with
    1 800-digit numerators); they are evaluated numerically now."""
    from fractions import Fraction

    from groundfield.io._formula import parse_impedance_formula

    seconds, outcome = _parse_in_child(text, _EAGER_GUARD_S)
    assert outcome == "accepted", outcome
    assert seconds < 0.3, f"{seconds:.2f} s"
    r = float(
        Fraction(int("9" * 299 + "7"), int("8" * 300))
        * Fraction(int("9" * 298 + "89"), int("7" * 299 + "1"))
        * Fraction(int("9" * 297 + "831"), int("6" * 299 + "7"))
    )
    assert complex(parse_impedance_formula(text)) == pytest.approx(value(r), rel=1e-15)


def test_exporter_formulas_never_reach_fractional_powers_exp_or_log() -> None:
    """The exporters write integer powers, products and sums only, so the
    floating-point evaluation of fractional powers and logarithms cannot
    change a formula they wrote (0.15.0 and 2026.11 alike)."""
    exported = [e for e in ACCEPT if e["origin"] != "hand-written"]
    assert len(exported) >= 100
    for entry in exported:
        tree = ast.parse(entry["formula"], mode="eval")
        for node in ast.walk(tree):
            assert not isinstance(node, ast.Call), entry["id"]
            if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Pow):
                exponent = node.right
                if isinstance(exponent, ast.UnaryOp):
                    exponent = exponent.operand
                assert isinstance(exponent, ast.Constant), entry["id"]
                assert type(exponent.value) is int, entry["id"]
