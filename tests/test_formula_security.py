pytestmark = pytest.mark.finding("10.01")

CORPUS = json.loads(
    (Path(__file__).parent / "data" / "formula_corpus.json").read_text(encoding="utf-8")
)
ACCEPT = CORPUS["accept"]
REJECT = CORPUS["reject"]
F_HZ = np.asarray(CORPUS["evaluation"]["f_Hz"], dtype=float)
RHO = float(CORPUS["evaluation"]["rho_Ohm_m"])

TIME_LIMIT_S = 2.0
MEMORY_LIMIT_BYTES = 32 * 2**20

#: Budget per rejected string, measured inside the worker process.
WORKER_TIME_LIMIT_S = 1.0
#: The worker is killed when a string takes longer than this (seconds;
#: ``GF_FORMULA_WORKER_DEADLINE_S`` overrides it, e.g. on a slow machine).
WORKER_DEADLINE_S = float(os.environ.get("GF_FORMULA_WORKER_DEADLINE_S", "20"))


def _with_marker(formula: str, marker: Path) -> str:
    """Insert a quoted marker-file path for the payloads that write one."""
    return formula.replace(CORPUS["marker_token"], repr(str(marker)))


# ---------------------------------------------------------------------
# Worker process: hostile strings never reach this interpreter first
# ---------------------------------------------------------------------

#: Address-space limit of the worker in bytes (it needs about 200 MiB), so a
#: string that exhausts memory fails there instead of starving the machine.
WORKER_MEMORY_LIMIT_BYTES = 2**30

#: Source of the worker. It reads one JSON list of ``{"id", "formula"}``
#: from stdin, reports ready after the imports and answers with one JSON
#: line per entry.
_WORKER_SOURCE = r"""
import json, sys, time
try:
    import resource
    resource.setrlimit(resource.RLIMIT_AS, (int(sys.argv[1]), int(sys.argv[1])))
except (ImportError, ValueError, OSError):  # no such limit on this platform
    pass
from groundfield.io._formula import FormulaError, parse_impedance_formula

entries = json.loads(sys.stdin.readline())
parse_impedance_formula("rho + j*f")  # warm-up: imports, SymPy caches
print(json.dumps({"ready": True}), flush=True)
for entry in entries:
    start = time.perf_counter()
    try:
        parse_impedance_formula(entry["formula"])
        outcome, message = "accepted", ""
    except FormulaError as exc:
        outcome, message = "rejected", str(exc)
    except BaseException as exc:  # any other error is a defect worth seeing
        outcome, message = "error:" + type(exc).__name__, str(exc)
    print(json.dumps({"id": entry["id"], "outcome": outcome,
                      "seconds": time.perf_counter() - start,
                      "message": message[:2000]}), flush=True)
"""


def _run_formula_worker(entries: list[dict], deadline_s: float) -> dict[str, dict]:
    """Parse ``entries`` in a worker process, at most ``deadline_s`` each.

    A worker that does not answer within the deadline (or dies) is killed,
    the entry is recorded as ``"timeout"`` and a new worker takes the
    remaining ones.
    """
    results: dict[str, dict] = {}
    pending = list(entries)
    while pending:
        proc = subprocess.Popen(
            [sys.executable, "-c", _WORKER_SOURCE, str(WORKER_MEMORY_LIMIT_BYTES)],
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
        )
        proc.stdin.write(json.dumps(pending) + "\n")
        proc.stdin.flush()
        lines: queue.Queue[str | None] = queue.Queue()

        def _pump(stream=proc.stdout, sink=lines) -> None:
            for line in stream:
                sink.put(line)
            sink.put(None)

        threading.Thread(target=_pump, daemon=True).start()
        try:
            ready = lines.get(timeout=120.0)  # imports, not part of the budget
        except queue.Empty:
            ready = None
        assert ready is not None and json.loads(ready) == {"ready": True}, ready
        answered, failure = 0, ""
        while answered < len(pending):
            try:
                line = lines.get(timeout=deadline_s)
            except queue.Empty:
                failure = f"no answer within {deadline_s:g} s"
                break
            if line is None:
                failure = "the worker process died"
                break
            record = json.loads(line)
            results[record["id"]] = record
            answered += 1
        proc.kill()
        proc.wait()
        if answered < len(pending):
            stuck = pending[answered]
            results[stuck["id"]] = {
                "id": stuck["id"],
                "outcome": "timeout",
                "seconds": math.inf,
                "message": failure,
            }
            answered += 1
        pending = pending[answered:]
    return results


@pytest.fixture(scope="module")
def worker_outcomes(tmp_path_factory) -> dict[str, dict]:
    """Outcome of every rejected corpus string, parsed in a worker process."""
    marker = tmp_path_factory.mktemp("worker") / "marker.txt"
    entries = [
        {"id": e["id"], "formula": _with_marker(e["formula"], marker)} for e in REJECT
    ]
    outcomes = _run_formula_worker(entries, WORKER_DEADLINE_S)
    assert not marker.exists(), "a corpus string was executed in the worker"
    return outcomes


def _require_worker_finished(outcomes: dict[str, dict], entry_id: str) -> None:
    """Fail instead of parsing in-process what the worker could not finish."""
    result = outcomes[entry_id]
    if result["outcome"] == "timeout":
        pytest.fail(f"{entry_id}: {result['message']} in the worker process")


def _document(formula: str) -> dict:
    return {
        "schema": SCHEMA_NAME,
        "schema_version": SCHEMA_VERSION,
        "name": "corpus",
        "description": None,
        "system_type": "TN",
        "voltage_level": 0.4,
        "impedance_formula": formula,
        "samples": {},
        "metadata": {},
    }


def _spec(formula: str) -> BusTypeSpec:
    """A spec built directly, i.e. without the validation on load."""
    return BusTypeSpec(
        name="corpus",
        description=None,
        system_type="TN",
        voltage_level=0.4,
        impedance_formula=formula,
        samples={
            "frequency_Hz": [],
            "rho_Ohm_m": [],
            "Z_real_Ohm": [],
            "Z_imag_Ohm": [],
        },
        metadata={},
    )


def _measured(call) -> tuple[BaseException | None, float, int]:
    """Run ``call()``; return (exception or None, seconds, peak bytes)."""
    tracemalloc.start()
    t0 = time.perf_counter()
    try:
        call()
        error = None
    except Exception as exc:  # noqa: BLE001 - returned to the caller
        error = exc
    finally:
        seconds = time.perf_counter() - t0
        peak = tracemalloc.get_traced_memory()[1]
        tracemalloc.stop()
    return error, seconds, peak


def _expected(entry: dict) -> np.ndarray:
    return np.asarray(entry["Z_real_Ohm"]) + 1j * np.asarray(entry["Z_imag_Ohm"])


