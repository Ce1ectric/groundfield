def test_evaluate_spec_does_not_run_code_from_a_formula(tmp_path: Path) -> None:
    marker = tmp_path / "marker.txt"
    payload = f"__import__('pathlib').Path({str(marker)!r}).write_text('ran')*0 + rho"
    try:
        with pytest.raises(EvaluateSpecError, match="not allowed"):
            evaluate_spec(_spec(payload), [50.0], 100.0)
    finally:
        assert not marker.exists(), "the formula string was executed"


def test_load_bustype_json_rejects_code_with_an_actionable_error(
    tmp_path: Path,
) -> None:
    marker = tmp_path / "marker.txt"
    path = tmp_path / "bustype.json"
    doc = _document(f"__import__('os').remove({str(marker)!r}) or rho")
    path.write_text(json.dumps(doc), encoding="utf-8")
    with pytest.raises(EvaluateSpecError) as excinfo:
        load_bustype_json(path)
    message = str(excinfo.value)
    assert "BusType document 'corpus'" in message
    assert "impedance_formula" in message
    assert "(U+0027)" in message  # names the quote character it refuses
    assert "never runs it as code" in message
    assert not marker.exists()


@pytest.mark.parametrize("entry", REJECT, ids=[e["id"] for e in REJECT])
def test_every_rejected_formula_fails_on_load_within_bounds(
    entry: dict, tmp_path: Path
) -> None:
    marker = tmp_path / "marker.txt"
    doc = _document(_with_marker(entry["formula"], marker))
    error, seconds, peak = _measured(lambda: BusTypeSpec.from_dict(doc))
    assert isinstance(error, EvaluateSpecError), f"accepted or wrong error: {error!r}"
    assert seconds < TIME_LIMIT_S
    assert peak < MEMORY_LIMIT_BYTES
    assert not marker.exists()


@pytest.mark.parametrize("entry", REJECT, ids=[e["id"] for e in REJECT])
def test_every_rejected_formula_fails_in_evaluate_spec_within_bounds(
    entry: dict, tmp_path: Path
) -> None:
    marker = tmp_path / "marker.txt"
    spec = _spec(_with_marker(entry["formula"], marker))
    error, seconds, peak = _measured(lambda: evaluate_spec(spec, F_HZ, RHO))
    assert isinstance(error, EvaluateSpecError), f"accepted or wrong error: {error!r}"
    assert seconds < TIME_LIMIT_S
    assert peak < MEMORY_LIMIT_BYTES
    assert not marker.exists()


@pytest.mark.parametrize("entry", ACCEPT, ids=[e["id"] for e in ACCEPT])
def test_every_accepted_formula_loads_and_gives_the_reference_values(
    entry: dict,
) -> None:
    spec = BusTypeSpec.from_dict(_document(entry["formula"]))
    z = evaluate_spec(spec, F_HZ, RHO)
    expected = _expected(entry)
    np.testing.assert_allclose(
        z, expected, rtol=1e-13, atol=1e-13 * np.max(np.abs(expected))
    )


def test_corpus_covers_both_exporter_generations_and_the_legacy_extremes() -> None:
    origins = {e["origin"] for e in ACCEPT}
    assert {"groundfield 0.15.0 exporter", "groundfield 2026.11 exporter"} <= origins
    legacy = [e["formula"] for e in ACCEPT if e["origin"].endswith("0.15.0 exporter")]
    longest_int = max(
        len(str(abs(n.value)))
        for text in legacy
        for n in ast.walk(ast.parse(text, mode="eval"))
        if isinstance(n, ast.Constant) and type(n.value) is int
    )
    assert longest_int >= 250  # the rationals of the 0.15.0 nsimplify step
    assert any("I" in text for text in legacy)  # lone complex pole
    classes = {e["class"] for e in REJECT}
    assert classes == {"code-execution", "resource-exhaustion", "out-of-grammar"}


