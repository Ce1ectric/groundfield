def test_parsing_never_compiles_or_evaluates_the_text(monkeypatch) -> None:
    import sympy
    from sympy.parsing import sympy_parser

    from groundfield.io._formula import FormulaError, parse_impedance_formula

    texts_ok = [e["formula"] for e in ACCEPT]
    texts_bad = [_with_marker(e["formula"], Path("/nonexistent/m")) for e in REJECT]
    for text in texts_ok:  # warm-up: lazy imports may legitimately exec
        parse_impedance_formula(text)

    calls: list[str] = []
    real_compile = builtins.compile

    def guarded_compile(source, filename, mode, flags=0, *args, **kwargs):
        if not flags & ast.PyCF_ONLY_AST:  # ast.parse itself is allowed
            calls.append("compile")
            raise AssertionError("formula text compiled to code")
        return real_compile(source, filename, mode, flags, *args, **kwargs)

    def forbidden(name: str):
        def _call(*args, **kwargs):
            calls.append(name)
            raise AssertionError(f"{name} called while parsing a formula")

        return _call

    monkeypatch.setattr(builtins, "compile", guarded_compile)
    monkeypatch.setattr(builtins, "eval", forbidden("eval"))
    monkeypatch.setattr(builtins, "exec", forbidden("exec"))
    monkeypatch.setattr(sympy, "sympify", forbidden("sympify"))
    monkeypatch.setattr(sympy_parser, "parse_expr", forbidden("parse_expr"))
    for text in texts_ok:
        parse_impedance_formula(text)
    for text in texts_bad:
        with pytest.raises(FormulaError):
            parse_impedance_formula(text)
    assert calls == []


@pytest.mark.parametrize("entry", ACCEPT, ids=[e["id"] for e in ACCEPT])
def test_parsed_expression_holds_only_allow_listed_objects(entry: dict) -> None:
    """What ``lambdify`` turns into code can only contain these objects."""
    import sympy as sp

    from groundfield.io._formula import parse_impedance_formula

    allowed = (
        sp.Add,
        sp.Mul,
        sp.Pow,
        sp.exp,
        sp.log,
        sp.Symbol,
        sp.Number,
        type(sp.I),
        type(sp.pi),
        type(sp.E),
    )
    expr = parse_impedance_formula(entry["formula"])
    for node in sp.preorder_traversal(expr):
        assert isinstance(node, allowed), type(node)
        if isinstance(node, sp.Symbol):
            assert node.name in {"f", "rho"}


@pytest.mark.parametrize(
    "text",
    [
        "(((10**60*f)**64)**64)**64",
        "(((((10**60*f)**64)**64)**64)**64)**64",
        "(((10**60+1)/10**60*f)**64)**64",
        "(((f-f+10**60)*f)**64)**64",
    ],
)
def test_power_of_a_symbolic_base_is_bounded_before_it_is_computed(text: str) -> None:
    """SymPy distributes ``(c*f)**n`` into ``c**n * f**n``.

    Bounding only symbol-free sub-expressions (the review prototype)
    accepts the first string after 24 s and a 15.7-million-digit
    integer; one more level does not terminate.
    """
    from groundfield.io._formula import FormulaError, parse_impedance_formula

    error, seconds, peak = _measured(lambda: parse_impedance_formula(text))
    assert isinstance(error, FormulaError)
    assert "power would create" in str(error)
    assert seconds < 0.5
    assert peak < 4 * 2**20


