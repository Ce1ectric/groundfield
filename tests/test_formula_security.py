"""BusType impedance formulas are parsed, never executed (finding 10.01).

Up to 0.15.0, ``evaluate_spec`` handed ``impedance_formula`` to
``sympy.sympify``, which evaluates the text as Python code: a crafted
BusType JSON file ran arbitrary code (review check S01) or exhausted
memory (``7**7**7`` builds a 696 000-digit integer, ``9**9**9**9`` does
not terminate). The formula is now parsed by the allow-list parser in
``groundfield.io._formula``, which builds the SymPy expression from the
Python syntax tree, and it is validated when a document is loaded.

``tests/data/formula_corpus.json`` holds the formulas every consumer
must accept (with reference values from the trusted legacy SymPy path)
and the strings it must reject. It is generated by the evidence script
``make_formula_corpus.py`` of the calendar release; groundinsight's own
guard is checked against the same corpus.
"""

from __future__ import annotations

import ast
import builtins
import json
import math
import time
import tracemalloc
import warnings
from pathlib import Path

import numpy as np
import pytest

from groundfield.io.groundinsight import (
    SCHEMA_NAME,
    SCHEMA_VERSION,
    BusTypeSpec,
    EvaluateSpecError,
    evaluate_spec,
    load_bustype_json,
    to_bustype_dict,
)

pytestmark = pytest.mark.finding("10.01")

CORPUS = json.loads(
    (Path(__file__).parent / "data" / "formula_corpus.json").read_text(encoding="utf-8")
)
ACCEPT = CORPUS["accept"]
REJECT = CORPUS["reject"]
F_HZ = np.asarray(CORPUS["evaluation"]["f_Hz"], dtype=float)
RHO = float(CORPUS["evaluation"]["rho_Ohm_m"])

TIME_LIMIT_S = 2.0
MEMORY_LIMIT_BYTES = 32 * 2**20


def _with_marker(formula: str, marker: Path) -> str:
    """Insert a quoted marker-file path for the payloads that write one."""
    return formula.replace(CORPUS["marker_token"], repr(str(marker)))


def _document(formula: str) -> dict:
    return {
        "schema": SCHEMA_NAME,
        "schema_version": SCHEMA_VERSION,
        "name": "corpus",
        "description": None,
        "system_type": "TN",
        "voltage_level": 0.4,
        "impedance_formula": formula,
        "samples": {},
        "metadata": {},
    }


def _spec(formula: str) -> BusTypeSpec:
    """A spec built directly, i.e. without the validation on load."""
    return BusTypeSpec(
        name="corpus",
        description=None,
        system_type="TN",
        voltage_level=0.4,
        impedance_formula=formula,
        samples={
            "frequency_Hz": [],
            "rho_Ohm_m": [],
            "Z_real_Ohm": [],
            "Z_imag_Ohm": [],
        },
        metadata={},
    )


def _measured(call) -> tuple[BaseException | None, float, int]:
    """Run ``call()``; return (exception or None, seconds, peak bytes)."""
    tracemalloc.start()
    t0 = time.perf_counter()
    try:
        call()
        error = None
    except Exception as exc:  # noqa: BLE001 - returned to the caller
        error = exc
    finally:
        seconds = time.perf_counter() - t0
        peak = tracemalloc.get_traced_memory()[1]
        tracemalloc.stop()
    return error, seconds, peak


def _expected(entry: dict) -> np.ndarray:
    return np.asarray(entry["Z_real_Ohm"]) + 1j * np.asarray(entry["Z_imag_Ohm"])


