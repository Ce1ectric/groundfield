def test_long_flat_sums_count_as_one_nesting_level() -> None:
    """A chain ``a + b - c + ...`` is one level: the partial fractions of a
    many-pole fit are limited by MAX_NODES, not by MAX_DEPTH."""
    from groundfield.io._formula import MAX_DEPTH, parse_impedance_formula

    n_terms = 3 * MAX_DEPTH // 2
    terms = [f"1/(f + {k + 1})" for k in range(n_terms)]
    expr = parse_impedance_formula(" + ".join(terms) + " - 2*f*rho*3/7/11")
    assert len(expr.args) == n_terms + 1


def test_many_pole_vector_fit_exports_and_loads() -> None:
    from groundfield.postprocess.vector_fitting import VectorFitResult

    rng = np.random.default_rng(3)
    poles, residues = [], []
    for _ in range(20):  # 20 conjugate pairs and 20 real poles
        p = complex(-rng.uniform(10.0, 1e4), rng.uniform(10.0, 1e4))
        r = complex(rng.uniform(-5.0, 5.0), rng.uniform(-5.0, 5.0))
        poles += [p, p.conjugate(), -rng.uniform(10.0, 1e4)]
        residues += [r, r.conjugate(), rng.uniform(-5.0, 5.0)]
    fit = VectorFitResult(
        poles=np.array(poles),
        residues=np.array(residues),
        R_inf=200.0,
        L_inf=1e-4,
        rms_error=0.0,
        fit_frequencies=np.array([0.0, 1000.0]),
        fit_values=np.zeros(2, dtype=complex),
    )
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        payload = to_bustype_dict(
            fit,
            name="many",
            system_type="TN",
            voltage_level=0.4,
            decimals=17,
            rho_at_fit=100.0,
        )
    grid = np.array([0.0, 50.0, 1000.0])
    z = evaluate_spec(BusTypeSpec.from_dict(payload), grid, 100.0)
    np.testing.assert_allclose(z, fit.evaluate(grid), rtol=1e-12)


def test_symbols_argument_sets_the_allowed_free_symbols() -> None:
    from groundfield.io._formula import FormulaError, parse_impedance_formula

    expr = parse_impedance_formula("f*rho + l", symbols=("f", "rho", "l"))
    assert {s.name for s in expr.free_symbols} == {"f", "rho", "l"}
    with pytest.raises(FormulaError, match=r"\['l'\]"):
        parse_impedance_formula("f*rho + l")
    with pytest.raises(ValueError, match="reserved"):
        parse_impedance_formula("f", symbols=("f", "pi"))
    with pytest.raises(ValueError, match="invalid symbol name"):
        parse_impedance_formula("f", symbols=("f", "2x"))


@pytest.mark.parametrize("digits", [1, 6, 12, 15, 17])
def test_format_then_parse_round_trips_within_the_rounding(digits: int) -> None:
    import sympy as sp

    from groundfield.io._formula import (
        format_impedance_formula,
        parse_impedance_formula,
    )

    f, rho = sp.symbols("f rho")
    j = sp.Symbol("j")
    expr = (
        sp.Float(2.739623036917992)
        - sp.Float(3108.4886146284425)
        / (2 * sp.pi * j * f + sp.Float(8414.047102128188))
        + sp.Float(1.2345678901234567e-7) * f * rho * (1 + sp.Float(0.25) * sp.I)
    )
    text = format_impedance_formula(expr, significant_digits=digits)
    parsed = parse_impedance_formula(text)
    numeric = sp.lambdify((f, rho), expr.subs(j, sp.I), "numpy")
    back = sp.lambdify((f, rho), parsed, "numpy")
    grid = np.array([0.0, 1.0, 50.0, 1000.0])
    ref = numeric(grid, 100.0)
    deviation = np.max(np.abs(back(grid, 100.0) - ref)) / np.max(np.abs(ref))
    assert deviation <= max(10.0 ** (1 - digits), 4e-15)  # floor: float64 noise
    for literal in ast.walk(ast.parse(text, mode="eval")):
        if isinstance(literal, ast.Constant) and type(literal.value) is float:
            mantissa = repr(abs(literal.value)).split("e")[0].replace(".", "")
            assert len(mantissa.strip("0")) <= digits


def test_format_impedance_formula_validates_its_input() -> None:
    import sympy as sp

    from groundfield.io._formula import format_impedance_formula

    f = sp.Symbol("f")
    assert format_impedance_formula(sp.Float(0.1) * f, significant_digits=40) == (
        format_impedance_formula(sp.Float(0.1) * f, significant_digits=17)
    )
    assert format_impedance_formula(sp.Float(2.5e-7) * f) == "2.5e-7*f"
    assert format_impedance_formula(sp.Float(25.0) + sp.I * f) == "j*f + 25"
    with pytest.raises(ValueError, match="positive integer"):
        format_impedance_formula(f, significant_digits=0)
    with pytest.raises(ValueError, match="non-finite"):
        format_impedance_formula(sp.nan * f)


